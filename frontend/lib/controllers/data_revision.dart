import 'package:flutter/foundation.dart';

/// 全局「数据变了」信号。
///
/// 问题背景：
/// 有些操作会改变**别的页面**里的列表内容 ——
/// 典型的就是在影片详情页里「储存 / 取消储存」，
/// 它会让「稍后观看」「播放清单」这些页面的内容变旧。
/// 但那些页面是常驻的（侧边栏页面放在 IndexedStack 里，
/// 个人主页也可能是被压在详情页下面），不会自己重新加载，
/// 于是返回后看到的还是旧数据（官网已经是新的了）。
///
/// 为什么会变旧一层层叠起来：
///   详情页改数据 -> 只有后端知道 -> 常驻页面还拿着自己的旧 state。
///
/// 做法：凡是会改变列表内容的操作，成功后 [bump] 一次；
/// 关心的页面监听它，收到变化就**静默刷新**（保留现有内容、
/// 不转圈，取到新数据后原地替换）。
///
/// 这样既「及时更新」又不用每次切页面都盲目重新请求。
class DataRevision {
  DataRevision._();

  /// 版本号，每次数据变化 +1
  static final ValueNotifier<int> revision = ValueNotifier<int>(0);

  /// 通知所有监听者：列表数据可能变了。
  static void bump() {
    revision.value++;
  }
}
